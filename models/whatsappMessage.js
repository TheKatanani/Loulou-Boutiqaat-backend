module.exports = (sequelize, DataTypes) => sequelize.define('WhatsAppMessage', {
  conversationId: { type: DataTypes.INTEGER, allowNull: false },
  metaMessageId: { type: DataTypes.STRING(255), unique: true },
  clientRequestId: { type: DataTypes.STRING(200), unique: true },
  direction: { type: DataTypes.STRING(12), allowNull: false },
  type: { type: DataTypes.STRING(30), allowNull: false },
  text: DataTypes.TEXT,
  mediaId: DataTypes.STRING(255),
  mimeType: DataTypes.STRING(120),
  filename: DataTypes.STRING(255),
  payload: DataTypes.JSON,
  sentByUserId: DataTypes.INTEGER,
  status: { type: DataTypes.STRING(20), allowNull: false },
  error: DataTypes.TEXT,
  occurredAt: { type: DataTypes.DATE, allowNull: false },
  automationState: { type: DataTypes.STRING(20), defaultValue: 'done' },
  automationAttempts: { type: DataTypes.INTEGER, defaultValue: 0 },
  automationLockedAt: DataTypes.DATE,
}, { indexes: [{ fields: ['conversationId', 'id'] }, { fields: ['automationState'] }] });
